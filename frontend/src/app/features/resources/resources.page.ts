export class ResourcesPage {
  protected readonly scenario = inject(ScenarioService);
  private readonly api = inject(ResourceService);
  private readonly destroyRef = inject(DestroyRef);

  protected readonly deptCols = ['dept', 'beds', 'util', 'doctors', 'nurses', 'weight'];
  protected readonly bedCols = ['ref', 'dept', 'status'];
  protected readonly staffCols = ['ref', 'role', 'dept', 'status'];
  protected readonly facilityCols = ['code', 'name', 'capacity', 'expected'];

  protected readonly error = signal<string | null>(null);
  protected readonly beds = signal<BedAvailability | null>(null);
  protected readonly staff = signal<StaffAvailability | null>(null);
  protected readonly departments = signal<DepartmentCapacity[]>([]);
  protected readonly facilities = signal<Facility[]>([]);

  protected readonly bedDept = signal('');
  protected readonly bedStatus = signal<BedStatus | ''>('');
  protected readonly bedPage = signal(1);
  protected readonly bedPageSize = signal(25);
  protected readonly bedRows = signal<BedRow[]>([]);
  protected readonly bedTotal = signal(0);

  protected readonly staffDept = signal('');
  protected readonly staffRole = signal<StaffRole | ''>('');
  protected readonly staffStatus = signal<StaffStatus | ''>('');
  protected readonly staffPage = signal(1);
  protected readonly staffPageSize = signal(25);
  protected readonly staffRows = signal<StaffRow[]>([]);
  protected readonly staffTotal = signal(0);

  constructor() {
    this.scenario.refreshState().pipe(takeUntilDestroyed(this.destroyRef)).subscribe({ error: () => undefined });
    // Re-read everything from the database whenever the data version changes.
    effect(() => {
      const v = this.scenario.dataVersion();
      if (v === null) return;
      untracked(() => this.loadAll());
    });
  }

  protected loadAll(): void {
    const fail = (e: unknown) => this.error.set(apiErrorMessage(e));
    this.error.set(null);
    this.api.bedAvailability().pipe(takeUntilDestroyed(this.destroyRef)).subscribe({ next: (b) => this.beds.set(b), error: fail });
    this.api.staffAvailability().pipe(takeUntilDestroyed(this.destroyRef)).subscribe({ next: (s) => this.staff.set(s), error: fail });
    this.api.departments().pipe(takeUntilDestroyed(this.destroyRef)).subscribe({ next: (d) => this.departments.set(d), error: fail });
    this.api.facilities().pipe(takeUntilDestroyed(this.destroyRef)).subscribe({ next: (f) => this.facilities.set(f), error: fail });
    this.loadBeds();
    this.loadStaff();
  }

  protected loadBeds(): void {
    this.api
      .beds({
        department: this.bedDept() || undefined,
        status: this.bedStatus() || undefined,
        page: this.bedPage(),
        pageSize: this.bedPageSize(),
      })
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe({
        next: (p) => {
          this.bedRows.set(p.items);
          this.bedTotal.set(p.total);
        },
        error: (e) => this.error.set(apiErrorMessage(e)),
      });
  }

  protected loadStaff(): void {
    this.api
      .staff({
        department: this.staffDept() || undefined,
        role: this.staffRole() || undefined,
        status: this.staffStatus() || undefined,
        page: this.staffPage(),
        pageSize: this.staffPageSize(),
      })
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe({
        next: (p) => {
          this.staffRows.set(p.items);
          this.staffTotal.set(p.total);
        },
        error: (e) => this.error.set(apiErrorMessage(e)),
      });
  }

  protected onBedPage(e: PageEvent): void {
    this.bedPage.set(e.pageIndex + 1);
    this.bedPageSize.set(e.pageSize);
    this.loadBeds();
  }

  protected onStaffPage(e: PageEvent): void {
    this.staffPage.set(e.pageIndex + 1);
    this.staffPageSize.set(e.pageSize);
    this.loadStaff();
  }
}
