export class DemoPage {
  private readonly demo = inject(DemoService);
  private readonly agent = inject(AgentService);
  private readonly providers = inject(ProvidersService);
  private readonly scenarios = inject(ScenarioService);
  private readonly auth = inject(AuthService);

  protected readonly steps = DEMO_STEPS;

  protected readonly statuses = signal<ProviderStatus[]>([]);
  protected readonly models = signal<ModelInfo[]>([]);
  protected readonly provider = signal<ProviderName | null>(null);
  protected readonly modelId = signal<string | null>(null);
  protected readonly temperature = signal(0.2);

  protected readonly question = signal('');
  protected readonly session = signal<DemoSessionView | null>(null);
  protected readonly checks = signal<Record<string, CitationCheck | null>>({});

  protected readonly loadError = signal<string | null>(null);
  protected readonly stepError = signal<string | null>(null);
  protected readonly notice = signal<string | null>(null);
  protected readonly busyScenario = signal<DemoScenario | null>(null);
  protected readonly confirmingReset = signal(false);
  protected readonly resetting = signal(false);

  protected readonly runs = computed(() => this.session()?.runs ?? []);
  protected readonly selectedStatus = computed(() => this.statuses().find((s) => s.provider === this.provider()) ?? null);
  protected readonly selectedModel = computed(
    () => this.models().find((m) => m.provider === this.provider() && m.model_id === this.modelId()) ?? null,
  );
  protected readonly canStep = computed(() => NEEDS_STEP.every((p) => this.auth.hasPermission(p)));
  protected readonly canReset = computed(() => this.auth.hasPermission(NEEDS_RESET));
  protected readonly canSubmit = computed(
    () => this.canStep() && this.busyScenario() === null && !this.resetting() && !!this.selectedModel() && !!this.selectedStatus()?.configured,
  );

  protected label = labelFromKey;
  protected fmt = formatMetric;

  constructor() {
    this.load();
  }

  protected scenarioLabel(key: DemoScenario): string {
    return this.steps.find((s) => s.key === key)?.label ?? key;
  }

  protected done(key: DemoScenario): boolean {
    return this.runs().some((r) => r.scenario_key === key);
  }

  protected checkFor(analysisRunId: string | null): CitationCheck | null {
    return analysisRunId ? (this.checks()[analysisRunId] ?? null) : null;
  }

  protected delta(d: number | null | undefined): string | null {
    if (d === null || d === undefined || d === 0) return null;
    const text = Number.isInteger(d) ? String(d) : d.toFixed(1);
    return d > 0 ? `(+${text})` : `(${text})`;
  }

  protected runStep(scenario: DemoScenario): void {
    const provider = this.provider();
    const model = this.modelId();
    if (!this.canSubmit() || !provider || !model) return;
    this.stepError.set(null);
    this.notice.set(null);
    this.busyScenario.set(scenario);
    this.demo.step({ scenario, provider, model, temperature: this.temperature(), mode: 'auto' }).subscribe({
      next: () => {
        this.busyScenario.set(null);
        this.loadSession(); // the backend session is the source of truth for the saved runs
        this.scenarios.refreshState().subscribe({ error: () => undefined }); // keep the toolbar's scenario/version current
      },
      error: (err: unknown) => {
        this.busyScenario.set(null);
        this.stepError.set(describeApiError(err));
        // A failed step may still have changed the data version: show the real state.
        this.scenarios.refreshState().subscribe({ error: () => undefined });
      },
    });
  }

  protected confirmReset(): void {
    this.resetting.set(true);
    this.stepError.set(null);
    this.demo.reset().subscribe({
      next: (r) => {
        this.resetting.set(false);
        this.confirmingReset.set(false);
        this.checks.set({});
        this.notice.set(`Reset: cleared ${r.cleared_runs} run(s); ${r.baseline_scenario} reloaded (data version ${r.data_version}). Ready to replay.`);
        this.loadSession();
        this.scenarios.refreshState().subscribe({ error: () => undefined });
      },
      error: (err: unknown) => {
        this.resetting.set(false);
        this.confirmingReset.set(false);
        this.stepError.set(describeApiError(err));
      },
    });
  }

  private load(): void {
    this.demo.question().subscribe({
      next: (q) => this.question.set(q),
      error: (err: unknown) => this.loadError.set(describeApiError(err)),
    });
    this.providers.status().subscribe({
      next: (s) => this.statuses.set(s),
      error: (err: unknown) => this.loadError.set(describeApiError(err)),
    });
    this.providers.models().subscribe({
      next: (m) => this.models.set(m),
      error: (err: unknown) => this.loadError.set(describeApiError(err)),
    });
    this.loadSession();
  }

  private loadSession(): void {
    this.demo.session().subscribe({
      next: (s) => {
        this.session.set(s);
        if (s.question) this.question.set(s.question);
        this.loadChecks(s);
      },
      error: (err: unknown) => this.loadError.set(describeApiError(err)),
    });
  }

  /** Citation verification lives with the agent run; fetch it so citation chips reflect the backend's check. */
  private loadChecks(s: DemoSessionView): void {
    for (const run of s.runs) {
      const id = run.analysis_run_id;
      if (!id || id in this.checks()) continue;
      this.checks.update((c) => ({ ...c, [id]: null }));
      this.agent
        .runDetail(id)
        .pipe(catchError(() => of(null)))
        .subscribe((detail) => this.checks.update((c) => ({ ...c, [id]: detail?.citation_check ?? null })));
    }
  }
}
