import { ChangeDetectionStrategy, Component, computed, input } from '@angular/core';
import { MatIconModule } from '@angular/material/icon';
import { PolicySources } from '../../shared/policy-sources.component';
import { formatCost, formatTokens } from '../playground/providers.service';
import { AgentRunResponse } from './agent.models';
import { formatMetric, labelFromKey, parseAnswer, prettyJson } from './answer-parser';

/** Read-only view of one agent run: data state, tools executed, retrieved policy, answer, and run facts. */
@Component({
  selector: 'app-agent-run-view',
  imports: [MatIconModule, PolicySources],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `
    @let r = run();
    <section class="badges" aria-label="Run summary">
      <span class="badge" [attr.data-status]="r.status">{{ r.status === 'completed' ? 'Completed' : 'Failed' }}</span>
      <span class="badge scenario" [attr.data-scenario]="r.scenario_key ?? 'none'">
        {{ r.scenario_name ?? 'No scenario' }} · data v{{ r.data_version ?? '?' }}
      </span>
      <span class="badge" [attr.data-mode]="r.mode">
        {{ r.mode === 'native' ? 'Native tool calling' : 'Fallback mode (deterministic tool plan)' }}
      </span>
      <span class="badge">{{ r.run_type === 'demo' ? 'Demo run' : 'Agent run' }}</span>
    </section>

    @if (r.mode === 'fallback') {
      <p class="note" role="note">
        <mat-icon aria-hidden="true">info</mat-icon>
        <span>
          The model did not choose the tools: the backend ran a fixed, data-driven tool plan and the model only wrote the
          answer from the verified results.{{ r.fallback_reason ? ' Reason: ' + r.fallback_reason + '.' : '' }}
        </span>
      </p>
    }
    @if (!r.data_version_consistent) {
      <p class="warn" role="alert">
        <mat-icon aria-hidden="true">warning</mat-icon>
        <span>The simulation data version changed while this run was in progress, so its tool results may mix two data states.</span>
      </p>
    }
    @if (r.status === 'failed') {
      <p class="warn" role="alert">
        <mat-icon aria-hidden="true">error</mat-icon>
        <span>{{ r.error ?? 'The run failed.' }}</span>
      </p>
    }

    <h3>Question</h3>
    <p class="question">{{ r.question }}</p>

    <h3>Metrics snapshot <span class="sub">verified data at the start of the run, data v{{ r.data_version ?? '?' }}</span></h3>
    @if (metrics().length === 0) {
      <p class="muted">No snapshot recorded.</p>
    } @else {
      <dl class="metrics">
        @for (m of metrics(); track m.key) {
          <div class="metric">
            <dt>{{ m.label }}</dt>
            <dd>{{ m.value }}</dd>
          </div>
        }
      </dl>
    }

    <h3>Tools executed <span class="sub">{{ r.tools_executed.length }} of max 5</span></h3>
    @if (r.tools_executed.length === 0) {
      <p class="muted">No tools were executed.</p>
    } @else {
      <ol class="tools">
        @for (t of r.tools_executed; track t.sequence) {
          <li>
            <details>
              <summary>
                <span class="seq">{{ t.sequence }}</span>
                <strong>{{ t.tool_name }}</strong>
                <span class="tstatus" [attr.data-status]="t.status">{{ t.status }}</span>
                <span class="dur">{{ t.duration_ms }} ms</span>
                @if (t.data_version !== null) {
                  <span class="dur">data v{{ t.data_version }}</span>
                }
              </summary>
              <div class="tbody">
                <div class="label">Validated arguments</div>
                <pre>{{ json(t.arguments) }}</pre>
                @if (t.error) {
                  <div class="label">Error</div>
                  <pre class="errtext">{{ t.error }}</pre>
                }
                @if (t.output) {
                  <div class="label">Result</div>
                  <pre>{{ json(t.output) }}</pre>
                }
              </div>
            </details>
          </li>
        }
      </ol>
    }

    <h3>Retrieved policy documents <span class="sub">from the knowledge base, not written by the model</span></h3>
    <app-policy-sources [sources]="r.retrieved_policies" [showQuery]="true" />

    <h3>Answer <span class="sub">generated by the model from the data and excerpts above</span></h3>
    @if (paragraphs().length === 0) {
      <p class="muted">No answer was produced.</p>
    } @else {
      <div class="legend">
        <span class="lg policy">Cites retrieved policy</span>
        <span class="lg general">No policy citation</span>
      </div>
      @for (p of paragraphs(); track $index) {
        <p class="para" [attr.data-kind]="p.kind">
          @if (!p.heading) {
            <span class="kind">{{ p.kind === 'policy' ? 'Policy-backed' : 'No policy citation' }}</span>
          }
          @for (s of p.segments; track $index) {
            @if (s.kind === 'citation') {
              <span class="cite" [attr.data-verified]="s.verified" [title]="s.verified ? 'Matches a retrieved document and page' : 'Not found among the retrieved sources'">
                {{ s.text }} {{ s.verified ? '✓' : '⚠ unverified' }}
              </span>
            } @else {
              {{ s.text }}
            }
          }
        </p>
      }
      <p class="citecheck" [attr.data-bad]="unverified() > 0">
        Citation check (done by the backend): {{ verified() }} verified, {{ unverified() }} unverified of
        {{ verified() + unverified() }} cited; {{ r.citation_check.retrieved_count ?? 0 }} excerpts were retrieved.
      </p>
    }

    <h3>Run details</h3>
    <dl class="facts">
      <div><dt>Provider</dt><dd>{{ r.provider }}</dd></div>
      <div><dt>Model</dt><dd>{{ r.model }}</dd></div>
      <div><dt>Temperature</dt><dd>{{ r.temperature ?? 'provider default' }}</dd></div>
      <div><dt>LLM calls</dt><dd>{{ r.llm_calls }}</dd></div>
      <div><dt>Latency</dt><dd>{{ r.latency_ms }} ms</dd></div>
      <div><dt>Tokens</dt><dd>{{ tokens() }}</dd></div>
      <div><dt>Est. cost</dt><dd>{{ cost() }}</dd></div>
      <div><dt>Run by</dt><dd>{{ r.created_by }}</dd></div>
      <div><dt>When</dt><dd>{{ r.created_at }}</dd></div>
    </dl>
    @if (r.data_disclosure) {
      <p class="note" role="note"><mat-icon aria-hidden="true">cloud</mat-icon><span>{{ r.data_disclosure }}</span></p>
    }
  `,
  styles: `
    :host { display: block; }
    h3 { margin: 20px 0 8px; font-size: 15px; }
    .sub { font-weight: 400; font-size: 12px; opacity: 0.7; margin-left: 6px; }
    .badges { display: flex; flex-wrap: wrap; gap: 8px; }
    .badge { padding: 2px 10px; border-radius: 12px; font-size: 12px; font-weight: 500; border: 1px solid var(--mat-sys-outline); }
    .badge[data-status='completed'] { border-color: #15803d; color: #15803d; }
    .badge[data-status='failed'] { border-color: #b3261e; color: #b3261e; }
    .badge[data-mode='fallback'] { border-color: #b45309; color: #b45309; }
    .badge.scenario[data-scenario='surge'] { border-color: #b91c1c; background: #fee2e2; color: #7f1d1d; }
    .note, .warn { display: flex; gap: 8px; align-items: flex-start; padding: 8px 12px; border-radius: 8px; font-size: 13px; margin: 10px 0 0; }
    .note { background: #e8eef7; color: #1f3a5f; }
    .warn { background: #fdecea; color: #8a1c14; }
    .question { margin: 0; white-space: pre-wrap; }
    .muted { color: var(--mat-sys-on-surface-variant); margin: 0; }
    .metrics { display: grid; grid-template-columns: repeat(auto-fill, minmax(190px, 1fr)); gap: 8px; margin: 0; }
    .metric { border: 1px solid var(--mat-sys-outline-variant); border-radius: 8px; padding: 6px 10px; }
    .metric dt { font-size: 11px; opacity: 0.7; }
    .metric dd { margin: 0; font-size: 18px; font-weight: 500; font-variant-numeric: tabular-nums; }
    .tools { list-style: none; margin: 0; padding: 0; display: flex; flex-direction: column; gap: 6px; }
    details { border: 1px solid var(--mat-sys-outline-variant); border-radius: 8px; padding: 6px 12px; }
    summary { cursor: pointer; display: flex; flex-wrap: wrap; gap: 10px; align-items: center; }
    .seq { display: inline-flex; width: 22px; height: 22px; border-radius: 50%; background: var(--mat-sys-primary); color: var(--mat-sys-on-primary); align-items: center; justify-content: center; font-size: 12px; }
    .tstatus { font-size: 12px; padding: 0 8px; border-radius: 10px; border: 1px solid #15803d; color: #15803d; }
    .tstatus:not([data-status='ok']) { border-color: #b3261e; color: #b3261e; }
    .dur { font-size: 12px; opacity: 0.7; }
    .tbody .label { font-size: 12px; font-weight: 600; margin-top: 8px; }
    pre { margin: 4px 0 0; padding: 8px; background: var(--mat-sys-surface-container); border-radius: 6px; overflow: auto; max-height: 260px; font-size: 12px; }
    .errtext { color: #8a1c14; }
    .legend { display: flex; gap: 12px; font-size: 12px; margin-bottom: 6px; }
    .lg { padding-left: 8px; border-left: 4px solid; }
    .lg.policy { border-color: #1d4ed8; }
    .lg.general { border-color: #9ca3af; }
    .para { margin: 0 0 8px; padding: 6px 12px; border-left: 4px solid #9ca3af; background: var(--mat-sys-surface-container-low); border-radius: 0 6px 6px 0; white-space: pre-wrap; }
    .para[data-kind='policy'] { border-left-color: #1d4ed8; background: #eef4ff; }
    .kind { display: block; font-size: 11px; font-weight: 600; opacity: 0.65; margin-bottom: 2px; text-transform: uppercase; letter-spacing: 0.04em; }
    .cite { font-weight: 500; border-radius: 4px; padding: 0 4px; background: #dcfce7; color: #14532d; }
    .cite[data-verified='false'] { background: #fee2e2; color: #7f1d1d; }
    .citecheck { font-size: 12px; margin: 4px 0 0; opacity: 0.8; }
    .citecheck[data-bad='true'] { color: #8a1c14; opacity: 1; font-weight: 500; }
    .facts { display: grid; grid-template-columns: repeat(auto-fill, minmax(200px, 1fr)); gap: 6px 16px; margin: 0; font-size: 13px; }
    .facts dt { font-size: 11px; opacity: 0.7; }
    .facts dd { margin: 0; overflow-wrap: anywhere; }
  `,
})
export class AgentRunView {
  readonly run = input.required<AgentRunResponse>();

  protected readonly metrics = computed(() =>
    Object.entries(this.run().snapshot_metrics ?? {}).map(([key, value]) => ({
      key,
      label: labelFromKey(key),
      value: formatMetric(value),
    })),
  );
  protected readonly paragraphs = computed(() => parseAnswer(this.run().answer, this.run().citation_check));
  protected readonly verified = computed(() => this.run().citation_check?.verified_count ?? 0);
  protected readonly unverified = computed(() => this.run().citation_check?.unverified_count ?? 0);
  protected readonly tokens = computed(() => formatTokens(this.run().usage));
  protected readonly cost = computed(() => formatCost(this.run().estimated_cost_usd));
  protected readonly json = prettyJson;
}
